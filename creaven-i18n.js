let currentLang = 'en';

function setLang(lang) {
  currentLang = lang;
  const t = i18n[lang];
  if (!t) return;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });
  document.documentElement.lang = ['ko','ja','zh','th','de','es','fr','pt','it','nl','sv','pl','ru','tr','ar','hi','vi'].includes(lang) ? lang : 'en';
}

// Language dropdown
function toggleLangMenu() {
  const dd = document.getElementById('langDropdown');
  const btn = document.getElementById('langToggle');
  dd.classList.toggle('open');
  btn.classList.toggle('open');
}
function selectLang(lang, label) {
  setLang(lang);
  document.getElementById('langToggle').textContent = label;
  document.getElementById('langDropdown').classList.remove('open');
  document.getElementById('langToggle').classList.remove('open');
}
document.addEventListener('click', function(e) {
  if (!e.target.closest('.lang-switcher')) {
    document.getElementById('langDropdown').classList.remove('open');
    document.getElementById('langToggle').classList.remove('open');
  }
});

